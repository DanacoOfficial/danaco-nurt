// Module:           website.scripts.build-icons
// Responsibility:   Writes the icon data module of the site from the Lucide icon set (ISC license) for the icons named in config/icons.ts.
// Dependencies:     node:fs, the Iconify JSON file of the Lucide set (path given as the first argument or in ICON_SOURCE).

import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = process.argv[2] ?? process.env.ICON_SOURCE;
if (!source) {
  console.error('usage: node scripts/build-icons.mjs LUCIDE_JSON_FILE');
  process.exit(2);
}

const configText = readFileSync(resolve(root, 'config/icons.ts'), 'utf8');
const names = [...configText.matchAll(/^\s+'([a-z0-9-]+)',$/gm)].map((match) => match[1]);
const set = JSON.parse(readFileSync(source, 'utf8'));
const lines = [];
const missing = [];
for (const name of names) {
  const direct = set.icons[name];
  const alias = set.aliases?.[name];
  const icon = direct ?? (alias ? set.icons[alias.parent] : undefined);
  if (!icon) {
    missing.push(name);
    continue;
  }
  lines.push(`  '${name}': ${JSON.stringify(icon.body)},`);
}
if (missing.length > 0) {
  console.error(`icons not found in the set: ${missing.join(', ')}`);
  process.exit(1);
}

const header = [
  '// Copyright (c) 2026 Danaco Official | Danaco Holding Group Sp. z o.o. All rights reserved.',
  '// Use is subject to license terms: see the LICENSE file or https://www.danaco-group.pl',
  '// https://github.com/DanacoOfficial | support@danaco-group.pl',
  '//',
  '// Module:           website.src.components.base.icon-data',
  `// Responsibility:   Bodies of the ${names.length} icons of the Lucide set (ISC license, https://lucide.dev), generated by scripts/build-icons.mjs. Do not edit by hand.`,
  '// Dependencies:     none.',
  '',
  `export const iconViewBox = '0 0 ${set.width ?? 24} ${set.height ?? 24}';`,
  '',
  'export const iconBodies: Record<string, string> = {',
];
const output = resolve(root, 'src/components/base/icon-data.ts');
mkdirSync(dirname(output), { recursive: true });
writeFileSync(output, [...header, ...lines, '};', ''].join('\n'));
console.log(`${output} written (${names.length} icons)`);
