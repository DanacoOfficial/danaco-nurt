"""Write the path data of the mark and the lockups into a TypeScript module.

The site draws the mark and the name of Danaco Nurt as inline SVG, coloured by
the CSS variables of the active theme. The geometry is read from the files of
the production pack of the identity (production identity 1.0.0), so the site
never redraws the mark.

Usage:

  build_brand_data.py PACK OUTPUT_FILE

PACK is the directory design/brand/production of the design repository. The
output is src/components/brand/brand-data.ts.
"""

import json
import re
import sys
from pathlib import Path

LOCKUPS = {
    "horizontal": "lockups/lockup-horizontal-color-dark.svg",
    "vertical": "lockups/lockup-vertical-color-dark.svg",
    "compact": "lockups/lockup-compact-color-dark.svg",
    "wordmark": "wordmark/wordmark-color-dark.svg",
}

ROLE_BY_COLOUR = {"#DDE1E6": "silver", "#C9A15A": "gold", "#C9CED5": "company", "#F6F7F8": "product"}


def read_paths(path: Path) -> tuple[str, dict[str, str]]:
    text = path.read_text(encoding="utf-8")
    view_box = re.search(r'<svg[^>]*viewBox="([^"]+)"', text)
    if view_box is None:
        raise ValueError(f"no viewBox in {path}")
    roles = {}
    for colour, data in re.findall(r'<path fill="([^"]+)"[^>]*\sd="([^"]+)"', text):
        roles[ROLE_BY_COLOUR[colour.upper()]] = data
    return view_box.group(1), roles


def main(argv: list[str]) -> int:
    if len(argv) != 3:
        print(__doc__)
        return 2
    pack, output = Path(argv[1]), Path(argv[2])
    identity = json.loads((pack / "identity.json").read_text(encoding="utf-8"))
    mark = identity["mark"]["paths_main"]
    box = identity["mark"]["box_main"]
    lines = [
        "// Copyright (c) 2026 Danaco Official | Danaco Holding Group Sp. z o.o. All rights reserved.",
        "// Use is subject to license terms: see the LICENSE file or https://www.danaco-group.pl",
        "// https://github.com/DanacoOfficial | support@danaco-group.pl",
        "//",
        "// Module:           website.src.components.brand.brand-data",
        "// Responsibility:   Path data of the mark and the lockups of the production identity 1.0.0, generated by scripts/build_brand_data.py. Do not edit by hand.",
        "// Dependencies:     none.",
        "",
        f"export const markViewBox = '{box[0]} {box[1]} {round(box[2] - box[0], 3)} {round(box[3] - box[1], 3)}';",
        f"export const markPaths = {{ silver: '{mark['left']}', gold: '{mark['right']}' }} as const;",
        "",
        "export interface LockupData {",
        "  readonly viewBox: string;",
        "  readonly silver?: string;",
        "  readonly gold?: string;",
        "  readonly company: string;",
        "  readonly product: string;",
        "}",
        "",
        "export const lockups: Record<'horizontal' | 'vertical' | 'compact' | 'wordmark', LockupData> = {",
    ]
    for name, relative in LOCKUPS.items():
        view_box, roles = read_paths(pack / relative)
        fields = [f"    viewBox: '{view_box}',"]
        for role in ("silver", "gold", "company", "product"):
            if role in roles:
                fields.append(f"    {role}: '{roles[role]}',")
            elif role == "company":
                fields.append("    company: '',")
        lines.append(f"  {name}: {{")
        lines.extend(fields)
        lines.append("  },")
    lines.append("};")
    lines.append("")
    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{output} written")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
